"""Writes e2e/titan.conf, e2e/minilm.conf and e2e/local.conf from keyvector.example.conf for one AWS account."""
import pathlib
import sys

if len(sys.argv) != 2 or not sys.argv[1].isdigit():
    sys.exit("usage: python e2e/make-configs.py <account-id>")
account = sys.argv[1]
here = pathlib.Path(__file__).resolve().parent
src = (here.parent / "keyvector.example.conf").read_text()


def conf(name, app, embedder_block, index):
    s = src.replace('keyspace-name = "media"', 'keyspace-name = "keyvector_e2e"')
    s = s.replace('application-name = "keyvector-media-movies"', f'application-name = "{app}"')
    s = s.replace('metadata-columns = ["genre", "release_date", "language"]', 'metadata-columns = ["genre", "release_date"]')
    start, end = s.index("  embedder {"), s.index("  sink {")
    s = s[:start] + embedder_block + "\n" + s[end:]
    s = s.replace('vector-bucket = "my-vector-bucket"', f'vector-bucket = "keyvector-e2e-{account}"')
    s = s.replace('vector-index = "movies"', f'vector-index = "{index}"')
    s = s.replace("  REGION = ${?AWS_REGION}\n", "")
    (here / name).write_text("# Generated by e2e/make-configs.py for the end-to-end test.\n" + s)


conf("titan.conf", "keyvector-e2e-titan", """  embedder {
    type = "bedrock"
    model = "amazon.titan-embed-text-v2:0"
    dimensions = 256
    batch-size = 1
    concurrency = 4
    normalize = true
  }""", "movies-titan")
conf("minilm.conf", "keyvector-e2e-minilm", """  embedder {
    type = "tei"
    url = "http://localhost:8080"
    dimensions = 384
    batch-size = 32
    concurrency = 2
    normalize = true
  }""", "movies-minilm")
# The in-process embedder, writing to the same index as TEI: same model, identical vectors.
conf("local.conf", "keyvector-e2e-local", """  embedder {
    type = "local"
    model = "sentence-transformers/all-MiniLM-L6-v2"
    model-revision = "1110a243fdf4706b3f48f1d95db1a4f5529b4d41"
    dimensions = 384
    batch-size = 32
    normalize = true
  }""", "movies-minilm")
# Chunking and reranking: the local embedder with 10-word chunks, so every row spans several
# chunks, and a cross-encoder for queries. Check with `e2e.py verify-chunks movies-minilm 10 2`.
s = (here / "local.conf").read_text()
s = s.replace('application-name = "keyvector-e2e-local"', 'application-name = "keyvector-e2e-chunked"')
s = s.replace("    chunk-words = 0\n", "    chunk-words = 10\n    chunk-overlap-words = 2\n", 1)
s = s.replace("  sink {", """  rerank {
    model = "cross-encoder/ms-marco-MiniLM-L6-v2"
    model-revision = "233902d25c440f23af6f7d6e94d2946bac0bee0a"
    candidates = 50
  }

  sink {""", 1)
(here / "chunked.conf").write_text(s)
print("wrote e2e/titan.conf, e2e/minilm.conf, e2e/local.conf and e2e/chunked.conf")
