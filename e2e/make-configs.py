"""Writes e2e/titan.conf and e2e/minilm.conf from keyvector.example.conf for one AWS account."""
import pathlib
import sys

if len(sys.argv) != 2 or not sys.argv[1].isdigit():
    sys.exit("usage: python e2e/make-configs.py <account-id>")
account = sys.argv[1]
here = pathlib.Path(__file__).resolve().parent
src = (here.parent / "keyvector.example.conf").read_text()


def conf(name, app, embedder_block, index):
    s = src.replace('keyspace-name = "media"', 'keyspace-name = "keyvector_e2e"')
    s = s.replace('application-name = "keyvector-media-movies"', f'application-name = "{app}"')
    s = s.replace('metadata-columns = ["genre", "release_date", "language"]', 'metadata-columns = ["genre", "release_date"]')
    start, end = s.index("  embedder {"), s.index("  sink {")
    s = s[:start] + embedder_block + "\n" + s[end:]
    s = s.replace('vector-bucket = "my-vector-bucket"', f'vector-bucket = "keyvector-e2e-{account}"')
    s = s.replace('vector-index = "movies"', f'vector-index = "{index}"')
    s = s.replace("  REGION = ${?AWS_REGION}\n", "")
    (here / name).write_text("# Generated by e2e/make-configs.py for the end-to-end test.\n" + s)


conf("titan.conf", "keyvector-e2e-titan", """  embedder {
    type = "bedrock"
    model = "amazon.titan-embed-text-v2:0"
    dimensions = 256
    batch-size = 1
    concurrency = 4
    normalize = true
  }""", "movies-titan")
conf("minilm.conf", "keyvector-e2e-minilm", """  embedder {
    type = "tei"
    url = "http://localhost:8080"
    dimensions = 384
    batch-size = 32
    concurrency = 2
    normalize = true
  }""", "movies-minilm")
print("wrote e2e/titan.conf and e2e/minilm.conf")
